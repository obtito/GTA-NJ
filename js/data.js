/* ============ 道路横断面 ============
 * 一比一不是把线画粗，而是把红线宽拆成真实分区：
 *   [ 侧石 0.25 ] 人行道 4.5 | 非机动车道 3.5 | 机动车道 3.5×lanes | 中央分隔带 4 | 对称
 * bands 的 lo/hi 是相对中心线的横向米数（-W/2 … +W/2），y 是相对路面标高的人行道抬升（米）。
 * kerbs 是侧石立面（路面 → 人行道顶），单独扫掠，不然人行道会像贴纸浮在沥青上。 */
export function roadSection(r) {
  const W = r.widthM || 40;
  const lanes = r.lanes || 3;
  const cls = r.cls || 'main';
  const median = r.median != null ? r.median : (cls === 'highway' ? 3 : 4);
  const sidewalk = r.sidewalk != null ? r.sidewalk : (cls === 'highway' ? 0 : 4.5);
  const curbW = 0.25;
  const half = W / 2;

  // 单侧：机非合计 = (红线 − 中央带 − 2×人行道 − 2×侧石) / 2
  let inner = (W - median - 2 * sidewalk - 2 * curbW) / 2;
  let hard = cls === 'highway' ? 3.0 : 0;      // 高速/快速路的硬路肩（应急带）
  let bike = cls === 'highway' ? 0 : 3.5;
  let aux = 0;                                 // 辅道：快速路的慢速车道（公交/卡车走这条）
  let verge = 0;                               // 剩余富余给土路肩/绿化带
  // 车道宽 = 扣掉硬路肩与非机动车道之后剩下的那半幅 ÷ 车道数。
  // 早先这里忘了减 bike，中山南路因此算出 4.42 m 的假车道，横断面总和比红线宽出 2.5 m/侧，
  // 多出来的部分既没铺装也没人管 —— 路面上就留下一圈 4.5 m 宽的空带（远看是草地）。
  let lane = (inner - hard - bike) / lanes;
  if (lane > 3.75) {                       // 车道撑不满整幅红线 —— 富余按「硬路肩 → 辅道 → 绿化带」下料
    lane = 3.75;
    let s = inner - hard - bike - lane * lanes;   // 单侧富余
    hard += Math.min(s, cls === 'highway' ? 0.5 : 1.0); s -= Math.min(s, cls === 'highway' ? 0.5 : 1.0);
    aux += Math.min(s, 3.5);                s -= Math.min(s, 3.5);
    verge += s;
  }
  if (lane < 3.2) {                       // 红线偏窄：先压硬路肩/辅道，再压非机动车道
    let need = (3.2 - lane) * lanes;
    const take = (v) => { const t = Math.min(v, need); need -= t; return t; };
    hard -= take(hard); aux -= take(aux); bike = Math.max(1.8, bike - need);
    lane = (inner - hard - bike - aux) / lanes;
  }
  if (lane < 3.0) lane = 3.0;             // 车道极限，宁可挤一点也别画成自行车道
  // 兜底：分区总和仍超过单侧红线时，按 辅道 → 硬路肩 → 非机动车道 的顺序回退（车道是硬指标）
  let over = hard + bike + aux + lane * lanes - inner;
  if (over > 0) {
    const cut = (v) => { const t = Math.min(v, over); over -= t; return v - t; };
    aux = cut(aux); hard = cut(hard); bike = cut(bike);
  }

  const bands = [];
  const add = (kind, lo, hi, y) => { if (hi - lo > 0.03) bands.push({ kind, lo, hi, y }); };
  // 先铺单侧（从 -half 向中央带），再整体镜像过去 —— 漏了镜像的话横断面只盖住 Half 红线。
  // 单侧用**游标**连续推进，而不是各自算 lo/hi：早先各带独立定位，非机动车道那条写成了
  // sadd(kind, hi, lo)（参数反了）被 `b - a > 0.03` 判负直接丢掉，路面上就少 3.5 m。
  const side = [];
  let cur = -half;
  const sadd = (kind, w, y) => {
    if (w > 0.03) { side.push({ kind, lo: cur, hi: cur + w, y }); cur += w; }
  };
  sadd('sidewalk', sidewalk, 0.16);
  sadd('curbtop', curbW, 0.16);
  sadd('hard', hard, 0);              // 硬路肩/应急带紧贴路缘（真实做法）
  sadd('bike', bike, 0);
  for (let i = 0; i < lanes; i++) sadd('motor', lane, 0);
  sadd('aux', aux, 0);
  // 收口：剩下的富余一律给土路肩/绿化，保证 -half → -median/2 整幅铺满、不留缝
  verge = -median / 2 - cur;
  sadd('verge', verge, 0);
  for (const b of side) add(b.kind, -b.hi, -b.lo, b.y);   // 镜像侧
  for (const b of side) add(b.kind, b.lo, b.hi, b.y);
  add('median', -median / 2, median / 2, 0.12);

  return { name: r.name, cls, W, lanes, median, sidewalk, bike, curbW, hard, aux, verge, lane, half, bands };
}
